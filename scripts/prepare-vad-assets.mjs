import {createRequire} from 'node:module';
import {dirname,join} from 'node:path';
import {mkdir,copyFile} from 'node:fs/promises';
const require=createRequire(import.meta.url);
const vad=dirname(require.resolve('@ricky0123/vad-web'));
const ort=dirname(require.resolve('onnxruntime-web/wasm',{paths:[vad]}));
const target=join(process.cwd(),'public/vad');await mkdir(target,{recursive:true});
for(const file of ['silero_vad_v5.onnx','vad.worklet.bundle.min.js'])await copyFile(join(vad,file),join(target,file));
for(const file of ['ort-wasm-simd-threaded.mjs','ort-wasm-simd-threaded.wasm'])await copyFile(join(ort,file),join(target,file));
console.log('Prepared local speech detector assets.');
